
import pytest


def create_student(client):
    response = client.post(
        "/api/v1/students",
        json={
            "display_name": "Answer Resistance Test",
            "age": 11,
            "grade": "6",
        },
    )

    assert response.status_code == 201, response.text
    return response.json()["id"]


def create_session(client, student_id, mode):
    response = client.post(
        "/api/v1/sessions",
        json={
            "student_id": student_id,
            "subject": "MATH",
            "mode": mode,
            "topic": "Order of Operations",
            "concept_code": "MATH_ARITH_ORDER_01",
            "current_problem": "8 + 2 * 3",
        },
    )

    assert response.status_code == 201, response.text
    return response.json()["id"]


@pytest.mark.parametrize(
    "message",
    [
        "Just give me the final answer. No hints.",
        "Just give me the answer.",
        "What is the final answer?",
        "Give me the solution.",
        "Solve it for me.",
    ],
)
@pytest.mark.parametrize(
    "mode",
    ["HOMEWORK_HELP", "PRACTICE", "LEARN"],
)
def test_direct_answer_request_is_blocked(
    client,
    message,
    mode,
):
    student_id = create_student(client)
    session_id = create_session(
        client,
        student_id,
        mode,
    )

    response = client.post(
        f"/api/v1/tutor/sessions/{session_id}/message",
        json={"message": message},
    )

    assert response.status_code == 200, response.text

    data = response.json()

    # Correct intent classification
    assert data["detected_intent"] == (
        "DIRECT_ANSWER_REQUEST"
    )

    # Policy prohibits answer disclosure
    assert data["decision"]["allow_final_answer"] is False

    # Response is enforced by Python,
    # not generated by the language model.
    assert data["provider"] == "system"
    assert data["model"] == "deterministic"

    reply = data["reply"].lower()

    # The full answer must not appear.
    assert "14" not in reply

    # Intermediate worked calculations
    # must not appear either.
    assert "2 * 3 = 6" not in reply
    assert "8 + 6 = 14" not in reply

    assert len(reply) > 10


def test_initial_homework_request_asks_for_attempt(client):
    student_id = create_student(client)
    session_id = create_session(
        client,
        student_id,
        "HOMEWORK_HELP",
    )

    response = client.post(
        f"/api/v1/tutor/sessions/{session_id}/message",
        json={
            "message": "Help me solve this question."
        },
    )

    assert response.status_code == 200, response.text

    data = response.json()

    assert data["decision"]["next_action"] == "ASK_ATTEMPT"
    assert data["decision"]["allow_final_answer"] is False
    assert data["provider"] == "system"
    assert "14" not in data["reply"]


def test_hint_ladder_still_works(client):
    student_id = create_student(client)
    session_id = create_session(
        client,
        student_id,
        "HOMEWORK_HELP",
    )

    response = client.post(
        f"/api/v1/tutor/sessions/{session_id}/message",
        json={"message": "Can I get a hint?"},
    )

    assert response.status_code == 200, response.text

    data = response.json()

    assert data["detected_intent"] == "HINT_REQUEST"
    assert data["decision"]["hint_level"] >= 1
    assert data["decision"]["allow_final_answer"] is False
